import {readFile, writeFile} from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const features = [
  ['typographySessions', 'typography-sessions'], ['sidebarGlass', 'glass'],
  ['fileTooltips', 'file-tooltips'], ['closePriority', 'close-priority'], ['sidechatShortcut', 'sidechat'],
];
// Feature modules intentionally have no static imports. Wrap their factories in
// lexical scopes rather than adding a bundler/runtime dependency to this plugin.
let body = '';
for (const [key, file] of features) {
  const source = await readFile(new URL(`src/features/${file}.js`, root), 'utf8');
  if (!source.startsWith('export function createFeature(require) {') || /\bimport\s/.test(source)) {
    throw new Error(`Unsupported feature module: ${file}`);
  }
  body += `const ${key} = (() => {\n${source.replace('export function', 'function')}\nreturn createFeature;\n})();\n`;
}
const orchestrator = await readFile(new URL('src/client.js', root), 'utf8');
body += orchestrator.replace('export function createPlugin', 'function createPlugin');
await writeFile(new URL('client.js', root), `// Generated by scripts/build.js. Edit src/ instead.\nwindow.__ModuleLoader__.load({\n  id: 'dsh-sanshi-ui-enhancements',\n  factory(require) {\n${body}\n    return createPlugin(require);\n  },\n});\n`);
console.log('Built dsh-sanshi-ui-enhancements/client.js');
